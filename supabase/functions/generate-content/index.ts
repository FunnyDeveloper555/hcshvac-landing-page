import { serve } from "https://deno.land/std@0.168.0/http/server.ts";
import { createClient } from "https://esm.sh/@supabase/supabase-js@2";

const corsHeaders = {
  "Access-Control-Allow-Origin": "*",
  "Access-Control-Allow-Headers": "authorization, x-client-info, apikey, content-type, x-supabase-client-platform, x-supabase-client-platform-version, x-supabase-client-runtime, x-supabase-client-runtime-version",
};

serve(async (req) => {
  if (req.method === "OPTIONS") {
    return new Response(null, { headers: corsHeaders });
  }

  try {
    const { type, prompt, content, title } = await req.json();
    const LOVABLE_API_KEY = Deno.env.get("LOVABLE_API_KEY");

    if (!LOVABLE_API_KEY) {
      throw new Error("LOVABLE_API_KEY is not configured");
    }

    let systemPrompt = "";
    let userPrompt = "";

    if (type === "spot_text") {
      systemPrompt = "You are a content summarization assistant. Generate a short, compelling spot text (1-2 sentences, max 150 characters) that captures the essence of the given content. Return only the spot text, no quotes or explanation.";
      const plainText = (content || "").replace(/<[^>]*>/g, " ").replace(/\s+/g, " ").trim();
      userPrompt = `Generate a spot text for this content:\n\nTitle: ${title || "Untitled"}\n\nContent: ${plainText.substring(0, 2000)}`;
    } else if (type === "spot_image") {
      // Use AI image generation model directly
      const plainText = (content || "").replace(/<[^>]*>/g, " ").replace(/\s+/g, " ").trim();
      const imagePrompt = `Generate a professional, high-quality editorial photograph that visually represents the following article. The image should be suitable as a blog/article spot image (thumbnail). No text overlays.\n\nTitle: ${title || "Untitled"}\n\nContent summary: ${plainText.substring(0, 500)}`;

      const imageResponse = await fetch("https://ai.gateway.lovable.dev/v1/chat/completions", {
        method: "POST",
        headers: {
          Authorization: `Bearer ${LOVABLE_API_KEY}`,
          "Content-Type": "application/json",
        },
        body: JSON.stringify({
          model: "google/gemini-2.5-flash-image",
          messages: [
            { role: "user", content: imagePrompt },
          ],
          modalities: ["image", "text"],
        }),
      });

      if (!imageResponse.ok) {
        const errorText = await imageResponse.text();
        console.error("AI image generation error:", imageResponse.status, errorText);
        throw new Error("Failed to generate image");
      }

      const imageData = await imageResponse.json();
      const imageBase64Url = imageData.choices?.[0]?.message?.images?.[0]?.image_url?.url;

      if (!imageBase64Url) {
        throw new Error("No image was generated by the AI model");
      }

      // Extract base64 data and upload to Supabase storage
      const base64Data = imageBase64Url.replace(/^data:image\/\w+;base64,/, "");
      const binaryData = Uint8Array.from(atob(base64Data), (c) => c.charCodeAt(0));

      const supabaseUrl = Deno.env.get("SUPABASE_URL")!;
      const supabaseServiceKey = Deno.env.get("SUPABASE_SERVICE_ROLE_KEY")!;
      const supabase = createClient(supabaseUrl, supabaseServiceKey);

      const fileName = `spot-images/${crypto.randomUUID()}.png`;

      const { error: uploadError } = await supabase.storage
        .from("company-images")
        .upload(fileName, binaryData, {
          contentType: "image/png",
          upsert: false,
        });

      if (uploadError) {
        console.error("Storage upload error:", uploadError);
        throw new Error("Failed to upload generated image");
      }

      const { data: publicUrlData } = supabase.storage
        .from("company-images")
        .getPublicUrl(fileName);

      return new Response(
        JSON.stringify({ imageUrl: publicUrlData.publicUrl }),
        { headers: { ...corsHeaders, "Content-Type": "application/json" } }
      );
    } else if (type === "editor_content") {
      systemPrompt = "You are a professional content writer. Generate well-structured HTML content based on the user's prompt. Use appropriate HTML tags (h2, h3, p, ul, ol, strong, em, blockquote, etc). Do NOT include <html>, <head>, <body>, or <doctype> tags. Return only the inner HTML content ready to insert into a rich text editor.";
      userPrompt = prompt || "Write a sample article.";
    } else {
      return new Response(
        JSON.stringify({ error: "Invalid type. Use 'spot_text', 'spot_image', or 'editor_content'." }),
        { status: 400, headers: { ...corsHeaders, "Content-Type": "application/json" } }
      );
    }

    const body: any = {
      model: "google/gemini-3-flash-preview",
      messages: [
        { role: "system", content: systemPrompt },
        { role: "user", content: userPrompt },
      ],
    };

    const response = await fetch("https://ai.gateway.lovable.dev/v1/chat/completions", {
      method: "POST",
      headers: {
        Authorization: `Bearer ${LOVABLE_API_KEY}`,
        "Content-Type": "application/json",
      },
      body: JSON.stringify(body),
    });

    if (!response.ok) {
      if (response.status === 429) {
        return new Response(JSON.stringify({ error: "Rate limit exceeded. Please try again later." }), {
          status: 429, headers: { ...corsHeaders, "Content-Type": "application/json" },
        });
      }
      if (response.status === 402) {
        return new Response(JSON.stringify({ error: "AI credits depleted. Please add funds." }), {
          status: 402, headers: { ...corsHeaders, "Content-Type": "application/json" },
        });
      }
      const errorText = await response.text();
      console.error("AI gateway error:", response.status, errorText);
      throw new Error("AI gateway error");
    }

    const data = await response.json();
    const text = data.choices?.[0]?.message?.content || "";
    return new Response(JSON.stringify({ result: text }), {
      headers: { ...corsHeaders, "Content-Type": "application/json" },
    });
  } catch (error) {
    console.error("generate-content error:", error);
    return new Response(
      JSON.stringify({ error: error instanceof Error ? error.message : "Unknown error" }),
      { status: 500, headers: { ...corsHeaders, "Content-Type": "application/json" } }
    );
  }
});
